def render_category_selector(role):
    """
    渲染顶部分类/单元选择器

    参数:
        role: 用户角色（student / teacher）

    返回:
        str - 当前选中的分类/单元 ID
    """
    # 根据角色获取状态 key 和配置
    state_key = "ai_assistant_category"
    config = get_suggested_config(role)

    # 初始化当前分类
    if state_key not in st.session_state:
        st.session_state[state_key] = get_default_category(role)

    # 如果角色变了，重置分类
    if st.session_state.get("ai_last_role") != role:
        st.session_state[state_key] = get_default_category(role)
        st.session_state["ai_last_role"] = role

    current_category = st.session_state[state_key]

    if role == "teacher":
        st.markdown("#### 📚 选择教研主题")
        st.caption("切换分类后，推荐问题会跟着变化哦～")
    else:
        st.markdown("#### 📚 选择学习单元")
        st.caption("切换单元后，推荐问题会跟着变化哦～")

    # 分类按钮
    categories = list(config.items())
    cols = st.columns(len(categories))

    for i, (cat_id, info) in enumerate(categories):
        with cols[i]:
            label = f"{info['icon']} {info['name']}"
            is_active = current_category == cat_id
            if st.button(
                label,
                key=f"cat_sel_{cat_id}",
                use_container_width=True,
                type="primary" if is_active else "secondary",
            ):
                st.session_state[state_key] = cat_id
                st.rerun()

    st.markdown("---")
    return current_category


