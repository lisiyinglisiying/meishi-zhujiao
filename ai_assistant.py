def _text_similarity(text1, text2):
    """
    计算两段文本的相似度（基于 SequenceMatcher）

    参数:
        text1: 文本1
        text2: 文本2

    返回:
        float - 相似度 0~1
    """
    return SequenceMatcher(None, text1.lower(), text2.lower()).ratio()


def _keyword_match_score(question, keywords):
    """
    计算问题与关键词的匹配得分

    参数:
        question: 用户问题
        keywords: 关键词列表

    返回:
        float - 匹配得分 0~1
    """
    question_lower = question.lower()
    matched = 0

    for kw in keywords:
        if kw.lower() in question_lower:
            matched += 1

    if not keywords:
        return 0.0

    return matched / len(keywords)


def find_best_answer(user_question, role="student", current_category=None):
    """
    从知识库中找到最佳匹配的答案

    参数:
        user_question: 用户的问题
        role: 用户角色（student / teacher）
        current_category: 当前选中的单元/分类ID（可选，优先匹配当前分类）

    返回:
        dict - {
            "found": bool, 是否找到答案
            "answer": str, 答案内容
            "question": str, 匹配到的标准问题
            "category_name": str, 所属单元/分类名称
            "related": list, 相关问题推荐列表
            "score": float, 匹配度得分
        }
    """
    all_knowledge = _get_role_knowledge(role)
    user_question = user_question.strip()

    if not user_question:
        return {
            "found": False,
            "answer": "",
            "question": "",
            "category_name": "",
            "related": [],
            "score": 0,
        }

    # 确定分类字段名（学生端用 unit_id，教师端用 category_id）
    id_field = "unit_id" if role == "student" else "category_id"
    name_field = "unit_name" if role == "student" else "category_name"

    # ---- 计算每个条目的匹配得分 ----
    scored_items = []

    for item in all_knowledge:
        # 1. 关键词匹配得分（权重 0.6）
        kw_score = _keyword_match_score(user_question, item["keywords"])

        # 2. 问题相似度得分（权重 0.4）
        sim_score = _text_similarity(user_question, item["question"])

        # 3. 如果有当前分类，给当前分类加额外权重
        category_bonus = 0.1 if (current_category and item.get(id_field) == current_category) else 0

        # 综合得分
        total_score = kw_score * 0.6 + sim_score * 0.4 + category_bonus
        total_score = min(total_score, 1.0)  # 上限 1.0

        scored_items.append((total_score, item))

    # 按得分从高到低排序
    scored_items.sort(key=lambda x: x[0], reverse=True)

    best_score, best_item = scored_items[0]

    # ---- 判断是否找到匹配答案 ----
    # 阈值：综合得分 >= 0.25
    found = best_score >= 0.25

    # ---- 收集相关问题推荐（前 3 个） ----
    related = []
    for score, item in scored_items[1:4]:
        if score > 0.1:  # 只有相关度还可以的才推荐
            related.append({
                "question": item["question"],
                "category_name": item.get(name_field, ""),
                "score": score,
            })

    return {
        "found": found,
        "answer": best_item["answer"] if found else "",
        "question": best_item["question"] if found else "",
        "category_name": best_item.get(name_field, "") if found else "",
        "related": related,
        "score": best_score,
    }


