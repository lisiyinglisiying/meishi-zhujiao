def _generate_ai_response(user_input, role, current_category):
    """
    生成 AI 回复内容（内部辅助函数）

    参数:
        user_input: 用户问题
        role: 用户角色
        current_category: 当前分类/单元 ID

    返回:
        str - AI 回复内容
    """
    # 查找知识库答案
    result = find_best_answer(user_input, role, current_category)

    if result["found"]:
        # 找到了知识库答案
        answer = result["answer"]
        # 加上来源标注
        source_note = f"\n\n---\n\n📌 **知识点来源：** {result['category_name']}\n\n"
        # 加上追问引导
        follow_up = get_follow_up_hint()
        full_answer = answer + source_note + follow_up

        # 相关问题推荐
        if result["related"]:
            related_text = "\n\n**🔗 你可能还想了解：**\n"
            for rel in result["related"][:2]:
                related_text += f"- {rel['question']}\n"
            full_answer += related_text
    else:
        # 没找到，用通用回复
        full_answer = generate_general_response(user_input, role)

    return full_answer


def _strip_code_blocks(text):
    """
    去除文本中的代码块标记（用于思考过程展示）

    参数:
        text: 原始文本

    返回:
        str: 去除代码块后的纯文本
    """
    # 移除 ```...``` 代码块
    text = re.sub(r'```[\s\S]*?```', '', text)
    # 移除 `inline` 代码标记
    text = re.sub(r'`([^`]+)`', r'\1', text)
    return text.strip()


